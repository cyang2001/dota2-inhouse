"""Build the replay display catalog from Valve ID tables and Chinese tooltips."""
import argparse
import json
import re
from pathlib import Path


ID_ROW = re.compile(r'^\s*"([a-z0-9_]+)"\s+"([1-9][0-9]*)"\s*$', re.MULTILINE)
TOOLTIP = re.compile(r'^\s*"dota_tooltip_ability_([a-z0-9_]+)(?::n)?"[ \t]*"((?:\\.|[^"\\\n])*)"', re.I | re.M)
PLACEHOLDER = re.compile(r'[+−-]?\{[sdf]:[^}]+\}(?:%|秒|点)?')
HAN = re.compile(r'[\u3400-\u9fff]')


def read(path):
    return path.read_text(encoding='utf-8-sig')


def display_label(key, text):
    text = re.sub(r'<[^>]+>', '', text).replace(r'\"', '"').strip()
    if key.startswith('special_bonus_') and key != 'special_bonus_attributes':
        # Talent tooltips can contain patch-dependent values. Retain their effect.
        text = PLACEHOLDER.sub('', text).strip(' +-−/%：')
        text = f'天赋 · {text}' if text else ''
    return text if HAN.search(text) else None


def build_catalog(ids741, ids742, chinese, feeds=()):
    patches = {'7.41': dict(ID_ROW.findall(read(ids741))), '7.42': dict(ID_ROW.findall(read(ids742)))}
    keys = set().union(*patches.values())
    labels = {}
    for key, text in TOOLTIP.findall(read(chinese)):
        key = key.lower()
        if key in keys and (label := display_label(key, text)):
            labels.setdefault(key, label)
    for feed in feeds:
        for entry in json.loads(read(feed))['result']['data']['itemabilities']:
            if entry['name'] in keys and (label := display_label(entry['name'], entry['name_loc'])):
                labels.setdefault(entry['name'], label)
    # Game actions lack tooltips. Patch notes and historical tooltips supply the remaining names.
    labels.update(
        ability_capture='占领前哨',
        ability_lamp_use='激活观察者',
        twin_gate_portal_warp='使用双生之门',
        special_bonus_attributes='属性附加',
        special_bonus_unique_muerta_calling_hp_regen='天赋 · 唤魂范围内按最大生命值恢复',
        item_desolator_2='寂灭',
        item_horn_of_battle_greater='大战斗号角',
    )

    ids = {}
    for patch, table in patches.items():
        index = {}
        for name, number in table.items():
            if name in labels:
                index.setdefault(number, set()).add(name)
        ids[patch] = {number: next(iter(names)) for number, names in index.items() if len(names) == 1}
    shared = {number: name for number, name in ids['7.41'].items() if ids['7.42'].get(number) == name}
    for patch in ids:
        ids[patch] = {number: name for number, name in ids[patch].items() if number not in shared}
    return {'labels': labels, 'ids': ids, 'shared': shared}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('ids741', type=Path)
    parser.add_argument('ids742', type=Path)
    parser.add_argument('chinese', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--feed', type=Path, action='append', default=[])
    args = parser.parse_args()
    data = build_catalog(args.ids741, args.ids742, args.chinese, args.feed)
    args.output.write_text(
        '// Generated by server/scripts/build-match-names.py.\nexport default ' +
        json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + ';\n',
        encoding='utf-8',
    )


if __name__ == '__main__':
    main()
